use serde::Serialize;

/// Domain crate category for each of the 45 `forensics2rust` tools.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ToolCategory {
    Evtx,
    Hive,
    Srum,
    Artifacts,
    Crash,
    Posture,
}

impl ToolCategory {
    /// Returns the CLI group / category slug (`"evtx"`, `"hive"`, etc.).
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Evtx => "evtx",
            Self::Hive => "hive",
            Self::Srum => "srum",
            Self::Artifacts => "artifacts",
            Self::Crash => "crash",
            Self::Posture => "posture",
        }
    }

    /// Returns the implementing Cargo crate name for this category.
    pub const fn crate_name(self) -> &'static str {
        match self {
            Self::Evtx => "forensics2rust-evtx",
            Self::Hive => "forensics2rust-hive",
            Self::Srum => "forensics2rust-srum",
            Self::Artifacts => "forensics2rust-artifacts",
            Self::Crash => "forensics2rust-crash",
            Self::Posture => "forensics2rust-posture",
        }
    }
}

