/// Finds a tool descriptor by its canonical `tool_id` (e.g. `"evtx.all"`).
pub fn find_tool(tool_id: &str) -> Option<&'static ToolDescriptor> {
    FORENSIC_TOOL_CATALOG.iter().find(|t| t.tool_id == tool_id)
}

/// Finds a tool descriptor by its CLI subcommand path (e.g. `"artifacts prefetch"`).
pub fn find_by_subcommand(cli_subcommand: &str) -> Option<&'static ToolDescriptor> {
    FORENSIC_TOOL_CATALOG
        .iter()
        .find(|t| t.cli_subcommand == cli_subcommand)
}

/// Returns an iterator over all tool descriptors belonging to `category`.
pub fn tools_by_category(category: ToolCategory) -> impl Iterator<Item = &'static ToolDescriptor> {
    FORENSIC_TOOL_CATALOG.iter().filter(move |t| t.category == category)
}

/// Returns an iterator over all 45 canonical `tool_id` strings.
pub fn all_tool_ids() -> impl Iterator<Item = &'static str> {
    FORENSIC_TOOL_CATALOG.iter().map(|t| t.tool_id)
}
